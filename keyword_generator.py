"""Backend pipeline: Trello -> image(s) -> Claude CLI -> title+13 tags -> update card.

No API keys: title/tags are generated by shelling out to the `claude` CLI
(Claude Code), so it uses whatever auth the CLI already has.

All user interaction and output goes through an `io` object (see gui.py for the
Tkinter one, and FakeIO in the tests) so this module never touches Tk and stays
runnable headless.
"""
import io as _io
import json
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unicodedata
import urllib.parse

import requests
from PIL import Image

def base_dir():
    """App directory: beside the exe when frozen, else beside this script.
    Both the saved config and output.json live here."""
    if getattr(sys, "frozen", False):
        return os.path.dirname(os.path.abspath(sys.executable))
    return os.path.dirname(os.path.abspath(__file__))


TRELLO_API_KEY = os.getenv("TRELLO_API_KEY", "").strip()
TRELLO_TOKEN = os.getenv("TRELLO_TOKEN", "").strip()
CLAUDE_MODEL = os.getenv("CLAUDE_MODEL", "claude-sonnet-5").strip()
REQUEST_TIMEOUT = 30
CLAUDE_TIMEOUT = 240
CONFIG_PATH = os.path.join(base_dir(), "config.json")

# Grid cell size each source image is thumbnailed to, and the max long edge of
# the merged image. Downscaling here is what keeps Claude's vision token cost
# down when a listing has many photos.
MERGE_CELL = 512
MERGE_MAX_EDGE = 1280


def configure_credentials(io):
    """Load Trello creds from config once; ask via io and persist if missing."""
    global TRELLO_API_KEY, TRELLO_TOKEN
    if not (TRELLO_API_KEY and TRELLO_TOKEN) and os.path.exists(CONFIG_PATH):
        try:
            with open(CONFIG_PATH) as f:
                cfg = json.load(f)
            TRELLO_API_KEY = TRELLO_API_KEY or cfg.get("TRELLO_API_KEY", "").strip()
            TRELLO_TOKEN = TRELLO_TOKEN or cfg.get("TRELLO_TOKEN", "").strip()
        except (OSError, json.JSONDecodeError):
            pass
    if not TRELLO_API_KEY:
        TRELLO_API_KEY = io.ask("Trello API key:", secret=True).strip()
    if not TRELLO_TOKEN:
        TRELLO_TOKEN = io.ask("Trello token:", secret=True).strip()
    try:
        with open(CONFIG_PATH, "w") as f:
            json.dump({"TRELLO_API_KEY": TRELLO_API_KEY, "TRELLO_TOKEN": TRELLO_TOKEN}, f)
        os.chmod(CONFIG_PATH, 0o600)
    except OSError:
        pass


def _norm(s):
    """Case/whitespace/Unicode-form insensitive (Vietnamese accents come as NFC or NFD)."""
    return " ".join(unicodedata.normalize("NFC", s).casefold().split())


def parse_board_id(raw):
    """Accept a board URL, card URL, board ID or board name. Pure string work;
    card links and names are resolved over the network in get_lists()."""
    raw = raw.strip().strip('"\'')
    match = re.search(r'trello\.com/b/([^/?#\s]+)', raw)
    return match.group(1) if match else raw


def _trello_get(path, **params):
    return requests.get(f"https://api.trello.com/1/{path}",
                        params={'key': TRELLO_API_KEY, 'token': TRELLO_TOKEN, **params},
                        timeout=REQUEST_TIMEOUT)


def _resolve_board(board):
    """Card link -> its board; otherwise a board name -> its ID. None if neither."""
    match = re.search(r'trello\.com/c/([^/?#\s]+)', board)
    if match:
        r = _trello_get(f"cards/{match.group(1)}", fields='idBoard')
        return r.json()['idBoard'] if r.status_code == 200 else None
    r = _trello_get("members/me/boards", fields='name')
    if r.status_code == 200:
        ids = [b['id'] for b in r.json() if _norm(b['name']) == _norm(board)]
        if len(ids) == 1:  # duplicate names -> refuse, a wrong board gets its cards overwritten
            return ids[0]
    return None


def get_lists(board_id, io):
    """Fetch all lists in a Trello board (board_id may also be a card link or board name)."""
    response = _trello_get(f"boards/{urllib.parse.quote(board_id, safe='')}/lists")
    if response.status_code in (400, 404):  # not an ID: try card link / board name
        resolved = _resolve_board(board_id)
        if resolved:
            response = _trello_get(f"boards/{resolved}/lists")
    if response.status_code == 200:
        return response.json()
    io.log(f"Error: Failed to fetch lists from board '{board_id}'. Status {response.status_code}: {response.text[:200]}")
    if response.status_code in (400, 404):
        io.log("  -> Không tìm thấy board (hoặc có 2 board trùng tên). Dán link board https://trello.com/b/<ID>/..., link card, hoặc đúng tên board.")
    elif response.status_code == 401:
        io.log(f"  -> Trello rejected key/token. Delete '{CONFIG_PATH}' and re-run to re-enter.")
    return None


def select_list(lists, io):
    """Pick a list by exact name or by number from a shown menu."""
    menu = "\n".join(f"  {i}. {l['name']}" for i, l in enumerate(lists, 1))
    choice = io.ask(f"Lists in board:\n{menu}\nEnter list number or exact name:").strip()
    for trello_list in lists:  # the web UI sends the list id
        if trello_list['id'] == choice:
            return choice
    if choice.isdigit():
        idx = int(choice) - 1
        if 0 <= idx < len(lists):
            return lists[idx]['id']
        io.log("Error: Number out of range.")
        return None
    for trello_list in lists:
        if trello_list['name'].lower() == choice.lower():
            return trello_list['id']
    io.log(f"Error: List '{choice}' not found.")
    return None


def get_cards_in_list(list_id, io):
    """Get all cards in a Trello list, with attachments."""
    url = f"https://api.trello.com/1/lists/{list_id}/cards"
    params = {'key': TRELLO_API_KEY, 'token': TRELLO_TOKEN, 'attachments': 'true'}
    response = requests.get(url, params=params, timeout=REQUEST_TIMEOUT)
    if response.status_code == 200:
        return response.json()
    io.log(f"Error: Failed to fetch cards from list '{list_id}'. Status {response.status_code}")
    return []


def image_attachments(card):
    """All image attachment URLs on a card, cover first if it is an image."""
    atts = [a for a in card.get('attachments', []) if (a.get('mimeType') or '').startswith('image/')]
    cover_id = (card.get('cover') or {}).get('idAttachment')
    atts.sort(key=lambda a: a.get('id') != cover_id)  # cover attachment first
    return [a['url'] for a in atts]


def get_image_urls_from_card(card, mode):
    """URLs to use for a card. mode 'cover' -> just the cover image (or none)."""
    urls = image_attachments(card)
    if mode == "cover":
        cover_id = (card.get('cover') or {}).get('idAttachment')
        return urls[:1] if (cover_id and urls) else []
    return urls


def extract_sku_from_title(card_name, io):
    """Extract SKU from card title in format '[SKU] title'."""
    match = re.match(r'^\[([^\]]*)\](?:\s+|$)(.*)?$', card_name)
    if match:
        return f"[{match.group(1)}]"
    io.log(f"Warning: No valid SKU in title '{card_name}'. Using empty SKU.")
    return ""


def fetch_image_bytes(image_url, io):
    """Download a Trello attachment (needs the OAuth header) and return raw bytes.
    The header carries the user's Trello creds, so only send it to Trello itself."""
    host = (urllib.parse.urlparse(image_url).hostname or "").lower()
    headers = {}
    if host == "trello.com" or host.endswith(".trello.com"):
        headers["Authorization"] = (
            f'OAuth oauth_consumer_key="{TRELLO_API_KEY}", oauth_token="{TRELLO_TOKEN}"')
    response = requests.get(image_url, headers=headers, timeout=REQUEST_TIMEOUT)
    if response.status_code != 200:
        io.log(f"Error: download failed (status {response.status_code}): {image_url}")
        return None
    if not response.headers.get("Content-Type", "").split(";")[0].strip().startswith("image/"):
        io.log(f"Error: not an image: {image_url}")
        return None
    return response.content


def merge_grid(images, cell=MERGE_CELL, max_edge=MERGE_MAX_EDGE):
    """Arrange PIL images into a near-square grid and downscale the result."""
    imgs = [im.convert("RGB") for im in images]
    for im in imgs:
        im.thumbnail((cell, cell))
    n = len(imgs)
    cols = math.ceil(math.sqrt(n))
    rows = math.ceil(n / cols)
    cw = max(im.width for im in imgs)
    ch = max(im.height for im in imgs)
    grid = Image.new("RGB", (cols * cw, rows * ch), (255, 255, 255))
    for i, im in enumerate(imgs):
        r, c = divmod(i, cols)
        grid.paste(im, (c * cw + (cw - im.width) // 2, r * ch + (ch - im.height) // 2))
    if max(grid.size) > max_edge:
        s = max_edge / max(grid.size)
        grid = grid.resize((round(grid.width * s), round(grid.height * s)))
    return grid


def build_image_file(card_id, urls, tmpdir, io):
    """Download all URLs, merge if >1, save a single JPEG. Returns path or None."""
    images = []
    for url in urls:
        data = fetch_image_bytes(url, io)
        if data:
            try:
                images.append(Image.open(_io.BytesIO(data)))
            except Exception as e:  # corrupt/unsupported image
                io.log(f"Warning: skip unreadable image ({e}): {url}")
    if not images:
        return None
    merged = images[0].convert("RGB") if len(images) == 1 else merge_grid(images)
    safe = re.sub(r'[^A-Za-z0-9_-]', '_', card_id)
    path = os.path.join(tmpdir, f"{safe}.jpg")
    merged.save(path, "JPEG", quality=85)
    return path


def find_claude():
    """Locate the claude CLI, including per-user no-admin install dirs whose
    PATH entry may not be live yet in a freshly-launched process."""
    exe = shutil.which("claude")
    if exe:
        return exe
    candidates = [
        os.path.expanduser(os.path.join("~", ".local", "bin", "claude.exe")),
        os.path.expanduser(os.path.join("~", ".local", "bin", "claude")),
        os.path.expanduser(os.path.join("~", "AppData", "Local", "Programs", "claude", "claude.exe")),
    ]
    return next((p for p in candidates if os.path.exists(p)), None)


def check_claude_connection(io):
    """Log whether the claude CLI is present AND can reach the API (logged in).
    Uses a cheap haiku ping so the health check costs almost nothing."""
    claude = find_claude()
    if not claude:
        io.log("Claude: NOT FOUND — chưa cài hoặc chưa vào PATH.")
        return False
    try:
        proc = subprocess.run(
            [claude, "-p", "reply with the single word OK",
             "--model", "claude-haiku-4-5", "--output-format", "json"],
            stdin=subprocess.DEVNULL, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=90,
        )
    except (subprocess.TimeoutExpired, OSError) as e:
        io.log(f"Claude: KẾT NỐI THẤT BẠI ({e}).")
        return False
    if proc.returncode == 0:
        io.log("Claude: kết nối thành công ✓")
        return True
    detail = (proc.stderr.strip() or proc.stdout.strip() or "(no output)")[:300]
    io.log(f"Claude: KẾT NỐI THẤT BẠI (exit {proc.returncode}): {detail}")
    io.log("  -> Đăng nhập: chạy 'claude' một lần trong terminal rồi thử lại.")
    return False


SEO_PROMPT = """Look only at the product in the photo(s) and write an Etsy listing title and tags for it.

Title rules:
- English, max 140 characters, no ALL CAPS, no emojis, no SKU.
- Start with the most-searched phrase a buyer would type for this exact item.
- Then add concrete details you can SEE: material, color, style, shape, use/room, and who it is for or the occasion if obvious.
- Separate phrases with commas or " | ". Do not repeat the same word more than twice.
- Do not invent sizes, brands or features that are not visible.

Tags rules:
- Exactly 13 tags, each max 20 characters including spaces, lowercase.
- Multi-word buyer search phrases (2-3 words), not single generic words.
- No duplicates, no near-duplicates, no plurals of another tag.
- Cover: item type, material, style, color, room/use, gift/occasion, and long-tail variants."""


def build_prompt(image_name, extra=""):
    """Built-in SEO rules, plus the seller's optional extra instructions."""
    extra = extra.strip()
    extra_part = (
        "\n\nAdditional instructions from the seller (follow these if they "
        f"conflict with the rules above):\n{extra}" if extra else ""
    )
    return (
        f"Read the image file {image_name} in the current directory. You are "
        f"an Etsy SEO assistant; the user owns this product photo.\n\n"
        f"{SEO_PROMPT}{extra_part}\n\nReturn ONLY a JSON object, no prose, with "
        'exactly two keys: "title" (a string) and "tags" (an array of 13 short string tags).'
    )


def generate_keywords_and_tags(image_path, io, extra=""):
    """Ask the claude CLI to look at image_path and return (title, tags)."""
    claude = find_claude()
    if not claude:
        io.log("Error: 'claude' CLI not found. Install Claude Code and log in, then re-run.")
        return None, None
    full_prompt = build_prompt(os.path.basename(image_path), extra)
    cmd = [
        claude, "-p", full_prompt,
        "--model", CLAUDE_MODEL,
        "--allowedTools", "Read",
        "--output-format", "json",
    ]
    # ponytail: every call pays for Claude Code's large system prompt (~$0.3 the
    # first card, cheaper after via 5-min prompt cache). If cost matters at scale,
    # switch to the Anthropic API with a key instead of the CLI.
    if is_stopped(io):  # Stop pressed while the image was being built
        return None, None
    proc = subprocess.Popen(
        cmd, cwd=os.path.dirname(image_path),
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True, encoding="utf-8", errors="replace",
    )
    io.proc = proc  # lets a Stop button kill it mid-card
    try:
        if is_stopped(io):  # Stop landed before io.proc was visible to it
            kill_proc(proc)
        stdout, stderr = proc.communicate(timeout=CLAUDE_TIMEOUT)
    except subprocess.TimeoutExpired:
        kill_proc(proc)
        proc.communicate()
        io.log(f"Error: claude timed out after {CLAUDE_TIMEOUT}s. Skipping.")
        return None, None
    finally:
        io.proc = None
    if is_stopped(io):
        return None, None
    proc.stdout, proc.stderr = stdout, stderr
    if proc.returncode != 0:
        # claude's real error usually lands on stdout (often as JSON), not stderr.
        detail = (proc.stderr.strip() or proc.stdout.strip() or "(no output)")[:500]
        io.log(f"Error: claude CLI failed (exit {proc.returncode}): {detail}")
        io.log("  -> Common cause: claude not logged in. Run 'claude' once in a "
               "terminal to sign in, then retry.")
        return None, None
    try:
        text = json.loads(proc.stdout)["result"]
    except (json.JSONDecodeError, KeyError, TypeError):
        io.log(f"Error: unexpected claude output: {proc.stdout[:300]}")
        return None, None
    return parse_title_tags(text, io)


def kill_proc(proc):
    """Kill proc and its children (claude may be a .cmd shim on Windows)."""
    if proc.poll() is not None:
        return
    if os.name == "nt":
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                       capture_output=True)
    else:
        proc.kill()


def is_stopped(io):
    """io may carry a threading.Event `stop` (web UI); console io has none."""
    stop = getattr(io, "stop", None)
    return bool(stop and stop.is_set())


def parse_title_tags(text, io):
    """Pull {title, tags} out of Claude's text (may be fenced/have prose)."""
    match = re.search(r'\{.*\}', text, re.DOTALL)
    if not match:
        io.log(f"Error: no JSON object in Claude output: {text[:300]}")
        return None, None
    try:
        obj = json.loads(match.group(0))
    except json.JSONDecodeError as e:
        io.log(f"Error: Claude output is not valid JSON ({e}): {text[:300]}")
        return None, None
    title = obj.get("title", "")
    tags = obj.get("tags", [])
    if not title or not tags:
        io.log(f"Error: Claude JSON missing/empty title or tags: {text[:300]}")
        return None, None
    return title, tags


def check_output(title, tags, io):
    """Log Etsy limit warnings; non-fatal."""
    if len(title) > 140:
        io.log(f"Warning: Title exceeds 140 chars (len {len(title)}). Continuing.")
    if len(tags) != 13:
        io.log(f"Warning: Tags count is {len(tags)}, expected 13. Continuing.")
    if not all(len(t) <= 20 for t in tags):
        io.log("Warning: One or more tags exceed 20 chars. Continuing.")
    if len(set(tags)) != len(tags):
        io.log("Warning: Duplicate tags found. Continuing.")


def update_card(card_id, sku, new_title, tags_list, io):
    """Update the title (SKU preserved) and description of a Trello card."""
    if not new_title or not tags_list:
        io.log(f"Error: Cannot update card '{card_id}' (missing title/tags).")
        return False
    check_output(new_title, tags_list, io)
    final_title = f"{sku} {new_title}".strip()
    url = f"https://api.trello.com/1/cards/{card_id}"
    params = {
        'key': TRELLO_API_KEY, 'token': TRELLO_TOKEN,
        'name': final_title, 'desc': ', '.join(tags_list),
    }
    response = requests.put(url, params=params, timeout=REQUEST_TIMEOUT)
    if response.status_code != 200:
        io.log(f"Error: Failed to update card '{card_id}'. Status {response.status_code}")
        if response.status_code == 401:
            io.log("  -> Token is read-only. Make a read,write token, delete "
                   f"'{CONFIG_PATH}', re-run.")
        return False
    io.log(f"Updated card '{sku}': DONE")
    return True


def run_pipeline(io):
    """Full flow, driven through io. Returns process exit code."""
    check_claude_connection(io)
    configure_credentials(io)
    if not (TRELLO_API_KEY and TRELLO_TOKEN):
        io.log("Error: Missing Trello credentials.")
        return 1

    mode_choice = io.ask("Image mode  [1] Cover only  [2] All listing images (merged)\nChoose 1/2:").strip()
    mode = "cover" if mode_choice == "1" else "all"
    io.log(f"Image mode: {mode}")

    extra = io.ask("AI Prompt (optional, Enter to skip):").strip()
    io.log(f"Extra prompt: {extra}" if extra else "Extra prompt: none (built-in SEO rules only)")
    board_id = parse_board_id(io.ask("Trello board ID or link:").strip())

    lists = get_lists(board_id, io)
    if not lists:
        io.log("Error: Cannot proceed without lists for this board.")
        return 1
    list_id = select_list(lists, io)
    if not list_id:
        return 1

    cards = get_cards_in_list(list_id, io)
    if not cards:
        io.log("Warning: No cards found in the specified list.")
        return 0

    results = []
    tmpdir = tempfile.mkdtemp(prefix="kwgen_")
    for n, card in enumerate(cards, 1):
        if is_stopped(io):
            io.log(f"\nĐã dừng: xử lý {len(results)}/{len(cards)} card.")
            break
        io.log(f"\n[{n}/{len(cards)}] Processing '{card['name']}' ({card['id']})")
        sku = extract_sku_from_title(card['name'], io)
        urls = get_image_urls_from_card(card, mode)
        title, tags, image_path, ok = None, None, None, False
        try:
            if not urls:
                io.log(f"Warning: No usable image for card '{card['id']}'. Skipping.")
            else:
                image_path = build_image_file(card['id'], urls, tmpdir, io)
                if image_path:
                    io.image(card['id'], image_path)  # show it in the UI
                    title, tags = generate_keywords_and_tags(image_path, io, extra)
                    if title and tags:
                        ok = update_card(card['id'], sku, title, tags, io)
                    elif not is_stopped(io):
                        io.log(f"Error: Skipping card '{card['id']}' (invalid Claude output).")
        except requests.RequestException as e:  # one card's network error must not kill the batch
            io.log(f"Error: network error on card '{card['id']}': {e}")
        io.result(card['id'], sku, title, tags, ok)
        results.append({
            "card_id": card['id'], "sku": sku,
            "title": title, "tags": tags, "ok": ok,
        })

    out_path = os.path.join(base_dir(), "output.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    io.log(f"\nSaved {len(results)} results to {out_path}")
    io.log("DONE")
    return 0


class ConsoleIO:
    """Plain terminal io, for running headless without the GUI."""

    def ask(self, prompt, secret=False):
        from getpass import getpass
        return getpass(prompt + " ") if secret else input(prompt + " ")

    def log(self, msg):
        print(msg)

    def image(self, card_id, path):
        print(f"  Image: {path}")

    def result(self, card_id, sku, title, tags, ok):
        pass


if __name__ == "__main__":
    try:
        raise SystemExit(run_pipeline(ConsoleIO()))
    except (EOFError, KeyboardInterrupt):
        print("\nCancelled.")
        raise SystemExit(130)
